/**
 * =====================================================================
 * JOL KONA — VERCEL BUILD-TIME FIREBASE CONFIG GENERATOR
 * =====================================================================
 *
 * WHAT THIS DOES:
 * Your site is fully static, and Vercel environment variables are NOT
 * automatically visible to browser JavaScript. This script runs once
 * during every Vercel deploy (see "buildCommand" in vercel.json) and
 * writes a real /firebase-config.js using the values you saved in:
 *
 *   Vercel Dashboard → your project → Settings → Environment Variables
 *
 * The real API key therefore lives ONLY in Vercel — never in git,
 * so GitHub secret scanning stays quiet and the placeholder file in
 * the repo keeps working unchanged for local development.
 *
 * REQUIRED VARIABLES (names must match exactly):
 *   FIREBASE_API_KEY
 *   FIREBASE_AUTH_DOMAIN
 *   FIREBASE_PROJECT_ID
 *   FIREBASE_STORAGE_BUCKET
 *   FIREBASE_MESSAGING_SENDER_ID
 *   FIREBASE_APP_ID
 *
 * OPTIONAL:
 *   FIREBASE_MEASUREMENT_ID
 *
 * If any required variable is missing, the build does NOT fail — the
 * placeholder config is kept and a warning is printed to the build log.
 * =====================================================================
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const ENV_MAP = {
  apiKey: "FIREBASE_API_KEY",
  authDomain: "FIREBASE_AUTH_DOMAIN",
  projectId: "FIREBASE_PROJECT_ID",
  storageBucket: "FIREBASE_STORAGE_BUCKET",
  messagingSenderId: "FIREBASE_MESSAGING_SENDER_ID",
  appId: "FIREBASE_APP_ID",
  measurementId: "FIREBASE_MEASUREMENT_ID", // optional
};

const config = {};
const missing = [];

for (const [key, envName] of Object.entries(ENV_MAP)) {
  const value = process.env[envName]?.trim();
  const looksReal = value && !value.startsWith("YOUR_");
  if (looksReal) {
    config[key] = value;
  } else if (key !== "measurementId") {
    missing.push(envName);
  }
}

if (missing.length > 0) {
  console.warn(
    `[firebase-config] Keeping placeholder config — these Vercel environment variables are missing or empty:\n` +
      `[firebase-config]   ${missing.join(", ")}\n` +
      `[firebase-config] Add them in Vercel → Settings → Environment Variables, then redeploy.`
  );
  process.exit(0); // never break the deploy
}

const fileContents = `/*
 * AUTO-GENERATED AT DEPLOY TIME — DO NOT COMMIT REAL VALUES TO GIT.
 * Generated by scripts/generate-firebase-config.mjs from Vercel
 * environment variables. The version tracked in the repository keeps
 * placeholders only; this generated copy exists only on the server.
 */
export const firebaseConfig = ${JSON.stringify(config, null, 2)};

export const isFirebaseConfigured = true;

export default firebaseConfig;
`;

writeFileSync(join(repoRoot, "firebase-config.js"), fileContents, "utf8");
console.log("[firebase-config] firebase-config.js generated from Vercel environment variables.");
